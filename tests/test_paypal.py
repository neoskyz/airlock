def test_mock_ids_are_explicit_and_stable():
    async def scenario():
        client = MockPayPal()
        for name in ["create_order", "create_payout"]:
            result = await client.execute(ToolCall(tool=name, amount=29, payee="a@example.com"), "fixed-request-id")
